const { chromium } = require('./browser-check/node_modules/playwright-core');
const fs = require('fs');
const crypto = require('crypto');
(async () => {
 const browser = await chromium.launch({ channel: 'msedge', headless: true });
 try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = 'http://toeic.localhost';
  const marker = 'ui-portal-check-' + Date.now();
  const email = marker + '@example.test';
  const password = crypto.randomBytes(18).toString('base64url');
  fs.writeFileSync('storage/framework/portal-check-data.json', JSON.stringify({ marker, email }));
  const adminPassword = fs.readFileSync('.env', 'utf8').match(/^ESKY_ADMIN_PASSWORD="?([^"\r\n]+)"?$/m)[1];
  async function login(path, user, pass) { await page.goto(base + path); await page.locator('#login-email').fill(user); await page.locator('#login-password').fill(pass); await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click(); }
  await login('/admin/login', 'admin@esky.local', adminPassword);
  await page.waitForURL('**/dashboard');
  await page.goto(base + '/users?type=student');
  await page.locator('#user-name').fill(marker);
  await page.locator('#user-email').fill(email);
  await page.locator('#user-password').fill(password);
  await page.getByRole('button', { name: 'Tạo tài khoản', exact: true }).click();
  await page.locator('tbody tr').filter({ hasText: email }).waitFor();
  console.log('Student account creation: OK');
  const csrf = decodeURIComponent((await context.cookies()).find(cookie => cookie.name === 'XSRF-TOKEN').value);
  const questionResult = await page.evaluate(async ({ csrf, marker }) => { const response = await fetch('/questions', { method: 'POST', headers: { 'X-XSRF-TOKEN': csrf, Accept: 'application/json', 'Content-Type': 'application/json' }, body: JSON.stringify({ part: 5, content: marker, options: { A: 'Correct option', B: 'Other option' }, correct_option: 'A', difficulty: 'medium' }) }); return { ok: response.ok, status: response.status }; }, { csrf, marker });
  if (!questionResult.ok) throw new Error('Question creation failed: ' + questionResult.status);
  await page.goto(base + '/exams');
  await page.locator('#exam-title').fill(marker);
  await page.locator('#exam-duration').fill('5');
  await page.getByRole('button', { name: 'Tạo đề nháp', exact: true }).click();
  let row = page.locator('tbody tr').filter({ hasText: marker });
  await row.waitFor();
  await row.getByRole('button', { name: 'Xem / thêm câu hỏi', exact: true }).click();
  const choice = page.locator('select[aria-label="Chọn câu hỏi thêm vào đề"] option').filter({ hasText: marker });
  await page.locator('select[aria-label="Chọn câu hỏi thêm vào đề"]').selectOption(await choice.getAttribute('value'));
  await page.getByRole('button', { name: 'Thêm vào đề', exact: true }).click();
  await page.locator('.exam-question-list li').filter({ hasText: marker }).waitFor();
  await row.getByRole('button', { name: 'Mở đề thi', exact: true }).click();
  await row.getByText('Đã mở thi', { exact: true }).waitFor();
  console.log('Exam creation, attach question, publish: OK');
  await page.goto(base + '/exam-accesses');
  const userId = await page.locator('#grant-user option').filter({ hasText: email }).getAttribute('value');
  const examId = await page.locator('#grant-exam option').filter({ hasText: marker }).getAttribute('value');
  await page.locator('#grant-user').selectOption(userId);
  await page.locator('#grant-exam').selectOption(examId);
  await page.getByRole('button', { name: 'Cấp quyền thi', exact: true }).click();
  await page.locator('tbody tr').filter({ hasText: email }).waitFor();
  await page.locator('#grant-user').selectOption(userId);
  await page.locator('#grant-mode').selectOption('session');
  await page.locator('#grant-session').fill('Ca tự đặt');
  await page.locator('#grant-start').fill('00:00');
  await page.locator('#grant-end').fill('23:59');
  await page.locator('#grant-attempts').fill('3');
  await page.getByRole('button', { name: 'Cấp quyền thi', exact: true }).click();
  await page.locator('tbody tr').filter({ hasText: 'Ca tự đặt' }).waitFor();
  await page.screenshot({ path: 'storage/framework/grants-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Admin grants mobile overflow');
  await page.screenshot({ path: 'storage/framework/grants-mobile.png', fullPage: true });
  console.log('Day grant and custom session grant: OK');
  await context.clearCookies();
  await login('/exam/login', email, password);
  await page.waitForURL('**/exam');
  await page.locator('.candidate-exams article').filter({ hasText: 'Thi theo ngày' }).waitFor();
  await page.screenshot({ path: 'storage/framework/candidate-home-mobile.png', fullPage: true });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Candidate home mobile overflow');
  page.on('dialog', dialog => dialog.accept());
  await page.locator('.candidate-exams article').filter({ hasText: 'Thi theo ngày' }).getByRole('button', { name: 'Bắt đầu thi', exact: true }).click();
  await page.waitForURL('**/exam/attempts/*');
  const attemptUrl = page.url();
  await page.locator('input[type="radio"][value="A"]').check();
  await page.waitForResponse(response => response.url().endsWith('/answers') && response.status() === 200);
  await page.reload();
  await page.locator('input[type="radio"][value="A"]:checked').waitFor();
  if (page.url() !== attemptUrl) throw new Error('Attempt changed on refresh');
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Attempt mobile overflow');
  await page.screenshot({ path: 'storage/framework/attempt-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Nộp bài', exact: true }).click();
  await page.locator('.result-score').waitFor();
  if (!(await page.locator('.result-score').innerText()).includes('1 / 1')) throw new Error('Incorrect result');
  await page.getByRole('link', { name: 'Về danh sách bài thi', exact: true }).click();
  await page.waitForURL('**/exam');
  const dayButton = page.locator('.candidate-exams article').filter({ hasText: 'Thi theo ngày' }).getByRole('button', { name: 'Bắt đầu thi', exact: true });
  if (!await dayButton.isDisabled()) throw new Error('Exhausted day grant still enabled');
  const sessionButton = page.locator('.candidate-exams article').filter({ hasText: 'Ca tự đặt' }).getByRole('button', { name: 'Bắt đầu thi', exact: true });
  if (await sessionButton.isDisabled()) throw new Error('Independent session grant disabled');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('PASS: separate login, account creation, exam publishing, both grant modes, auto-save/refresh, submit/result, independent quota, mobile layout');
 } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
